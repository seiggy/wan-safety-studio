"""Ports: the only things use cases know about storage and media tooling."""
from __future__ import annotations

from pathlib import Path
from typing import Protocol


class Store(Protocol):
    def exists(self, key: str) -> bool: ...
    def read(self, key: str) -> bytes | None: ...
    def write(self, key: str, data: bytes, overwrite: bool = True) -> None: ...
    def upload(self, key: str, path: Path, overwrite: bool = False) -> None: ...
    def download(self, key: str, path: Path) -> None: ...
    def list(self, prefix: str) -> list[str]: ...


class MediaTools(Protocol):
    def probe(self, video: Path) -> dict: ...
    def extract_frames(self, video: Path, out: Path, fps: float, limit: int) -> list[Path]: ...


class ComputeTarget(Protocol):
    """Runs a trainer image to completion. Implementations: local Docker now; Azure ML on the shared generation node later."""
    name: str

    def run(self, image: str, args: list[str], data: Path, out: Path, log: Path) -> int: ...
